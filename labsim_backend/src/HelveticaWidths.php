    /** Ancho en puntos de $text (ya en WinAnsi de un solo byte) a $size pt. */
    public static function width(string $text, float $size, bool $bold = false): float
    {
        $table = $bold ? self::BOLD : self::REGULAR;
        $total = 0;
        $len = strlen($text);
        for ($i = 0; $i < $len; $i++) {
            $ord = ord($text[$i]);
            $total += $table[$ord] ?? self::DEFAULT_WIDTH;
        }
        return $total * $size / 1000.0;
    }
